# --------------------------------------------------------------------------- the set replays


class TestTheSetReplays:
    @pytest.mark.parametrize("family", FAMILIES)
    def test_every_vector_in_the_family_reproduces(self, family):
        """No skip, no tolerance: every vector's entrypoint returns what the vector expects."""
        vectors = VECTORS.get(family)
        assert vectors, f"the set carries no {family} family"
        failures = []
        for vector in vectors:
            why = R.check_vector(vector, BLOBS)
            if why is not None:
                failures.append("%s: %s" % (vector["id"], why))
        assert not failures, "%d of %d %s vectors do not reproduce:\n  %s" % (
            len(failures), len(vectors), family, "\n  ".join(failures[:10])
        )

    def test_the_whole_set_replays_and_nothing_is_left_out(self):
        counts, failures = R.replay_set(VECTORS, BLOBS)
        assert not failures
        replayed = sum(row["vectors"] for row in counts.values())
        assert replayed == len(ALL) == INDEX["vectors"], (
            "the index counts %d vectors, the family files hold %d, the replay saw %d"
            % (INDEX["vectors"], len(ALL), replayed)
        )

    def test_the_replay_calls_the_shipped_functions_not_a_recorder_wrapper(self):
        """Importing the recorder installs wrappers into `styxx.v8`; a replay must not use them."""
        assert certmod.check.__module__ == "styxx.v8.cert"
        assert floormod.decide.__module__ == "styxx.v8.floor"
        assert R.RUNNERS.keys() == ENTRYPOINTS.keys()


