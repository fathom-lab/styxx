class TestTheIndex:
    def test_set_sha256_is_over_the_index_without_itself_or_its_provenance(self):
        core = {k: v for k, v in INDEX.items() if k not in ("set_sha256", "provenance")}
        assert hashlib.sha256(canonical_bytes(core)).hexdigest() == INDEX["set_sha256"]

    @pytest.mark.parametrize("family", FAMILIES)
    def test_each_family_file_hashes_to_what_the_index_says(self, family):
        row = INDEX["families"][family]
        data = (SET_DIR / row["file"]).read_bytes()
        assert hashlib.sha256(data).hexdigest() == row["sha256"]
        assert row["count"] == len(VECTORS[family])

    def test_the_blob_store_hashes_to_what_the_index_says(self):
        data = (SET_DIR / INDEX["blobs"]["file"]).read_bytes()
        assert hashlib.sha256(data).hexdigest() == INDEX["blobs"]["sha256"]
        assert INDEX["blobs"]["count"] == len(BLOBS)

    def test_the_index_counts_the_vectors_each_entrypoint_produced(self):
        counted = {name: 0 for name in ENTRYPOINTS}
        for vector in ALL:
            counted[vector["entrypoint"]] += 1
        for name, row in INDEX["entrypoints"].items():
            assert row["vectors"] == counted[name], name
            assert row["family"] == ENTRYPOINTS[name]

    def test_the_sources_are_the_ones_the_contract_names(self):
        assert tuple(INDEX["sources"]) == SOURCES
        for path in SOURCES:
            assert (ROOT / path).is_file()


class TestTheHonestRemainder:
    """`index.unvectored` is what the set does not reach. A gap is named, never inferred."""

    def test_every_reason_kind_is_either_reached_or_listed(self):
        reached = set()
        for vector in VECTORS["cert"]:
            reached |= set(vector["expect"].get("reason_kinds") or [])
        listed = set(INDEX["unvectored"]["reason_kinds"])
        assert reached & listed == set(), "a kind cannot be both reached and unvectored"
        assert reached | listed == set(REASON_KINDS)

    def test_every_channel_verdict_is_either_reached_or_listed(self):
        reached = {v["expect"]["verdict"] for v in VECTORS["decide"]
                   if v["expect"]["outcome"] == "verdict"}
        listed = set(INDEX["unvectored"]["channel_verdicts"])
        assert reached & listed == set()
        assert reached | listed == set(floormod.CHANNEL_VERDICTS)

    def test_every_gap_carries_a_note_that_says_why(self):
        notes = INDEX["unvectored"]["notes"]
        gaps = []
        for kind, key in (("reason_kind", "reason_kinds"), ("exit_code", "exit_codes"),
                          ("channel_verdict", "channel_verdicts"), ("entrypoint", "entrypoints")):
            gaps += ["%s:%s" % (kind, item) for item in INDEX["unvectored"][key]]
        assert sorted(notes) == sorted(gaps)
        unexplained = [k for k, v in notes.items() if v == "no note: an unexplained gap"]
        assert not unexplained, "a gap with no account of why: %s" % unexplained

    def test_every_skipped_call_says_which_test_made_it_and_why(self):
        rows = INDEX["unvectored"]["skipped"] + INDEX["unvectored"]["sources"]
        assert rows, "the set claims to have carried every call it saw"
        for row in rows:
            assert row["source"].split("::")[0] in SOURCES
            assert row["reason"]

    def test_the_property_tests_are_named_and_none_of_them_produced_a_vector(self):
        property_tests = {row["source"] for row in INDEX["unvectored"]["sources"]}
        assert property_tests
        produced = {source for vector in ALL for source in vector["sources"]}
        assert property_tests & produced == set()


