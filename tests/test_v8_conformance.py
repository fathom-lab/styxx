class TestTheBlobStore:
    def test_every_blob_hashes_to_its_key(self):
        for sha, payload in BLOBS.items():
            raw = base64.b64decode(payload, validate=True)
            assert hashlib.sha256(raw).hexdigest() == sha

    def test_every_blob_is_canonical_json_that_round_trips(self):
        for sha in BLOBS:
            raw = R.blob_bytes(BLOBS, sha)
            assert canonical_bytes(json.loads(raw.decode("utf-8"))) == raw

    def test_the_store_carries_exactly_what_the_vectors_name(self):
        named = set()
        for vector in ALL:
            named |= R.blob_refs(vector)
        missing = named - set(BLOBS)
        assert not missing, "vectors name blobs the store does not carry: %s" % sorted(missing)[:5]
        orphans = set(BLOBS) - named
        assert not orphans, "the store carries blobs nothing names: %s" % sorted(orphans)[:5]

    def test_the_result_body_a_diff_digests_is_carried_so_a_move_can_be_diffed(self):
        """`exit` vectors pin a hash; the bytes behind it are in the store, not only the hash."""
        outcomes = [v for v in VECTORS["exit"] if "result_sha256" in v["expect"]]
        assert outcomes
        for vector in outcomes:
            body = R.blob_value(BLOBS, vector["expect"]["result_sha256"])
            assert body["kind"] == "verify"
            assert body["overall"] == vector["expect"]["verdict"]


