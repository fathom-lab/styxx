"""The committed styxx.v8 conformance set: it replays, it is addressed by its own bytes, and the
instrument that says so can fail.

Built to `styxx/v8/INTERFACES_layer2.md` section 10. Nothing here skips. A replay test that cannot
fail is a silent pass, so `TestTheInstrumentCanFail` breaks the set and the implementation on
purpose and asserts that the checks below notice -- without those, "every vector passes" would be a
sentence about the test file rather than about `styxx.v8`.

The set is data, and this file only ever reads it. It is regenerated by
`python conformance/v8/gen_vectors.py`, which refuses to write when a committed vector's outcome
has moved; a moved core is a finding about `styxx.v8` and belongs in a commit that says so.
"""
